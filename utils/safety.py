"""紧急症状识别与安全护栏。

健康类应用的核心安全逻辑：当用户描述可能危及生命的情况时，
应立即引导其拨打急救电话，而不是由 AI 提供常规建议。

设计要点（在「不漏报」与「不误报」之间取得平衡）：
1. 两级判定 —— 表述本身即指向危急的（如「心跳骤停」）单独触发；
   常见症状（如「胸闷」）需与加重修饰词同现才触发，避免把普通咨询当成急救。
2. 语境过滤 —— 问「如何预防中风」是在咨询知识，不是在描述自身危急，不应触发。
3. 否定过滤 —— 「我没有胸痛」不应触发。
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# 一级：表述本身即明确指向危及生命的情况，单独出现即触发。
# ---------------------------------------------------------------------------
EMERGENCY_KEYWORDS: tuple[str, ...] = (
    # 心血管 / 脑血管
    "心跳骤停", "心脏骤停", "心肌梗死", "心梗", "心绞痛",
    "偏瘫", "口角歪斜", "一侧肢体无力", "中风征兆", "脑出血", "脑梗",
    # 呼吸
    "窒息", "呼吸停止", "喉头水肿", "无法呼吸", "喘不上气", "嘴唇发紫",
    # 出血 / 创伤
    "大出血", "血流不止", "吐血", "咯血", "便血不止", "断肢", "严重外伤",
    # 意识 / 神经
    "意识丧失", "昏迷", "晕厥", "抽搐", "癫痫持续", "瞳孔散大",
    # 中毒 / 意外
    "中毒", "误食", "服毒", "农药", "一氧化碳", "溺水", "触电",
    # 产科 / 儿童危急
    "宫外孕", "子痫", "高热惊厥", "新生儿窒息",
)

# ---------------------------------------------------------------------------
# 二级：常见症状，需叠加「加重修饰词」才判定为紧急。
# 例如「胸闷」本身不触发，「剧烈胸闷、伴大汗」才触发。
# ---------------------------------------------------------------------------
SEVERE_SYMPTOMS: tuple[str, ...] = (
    "胸痛", "胸闷", "胸口", "心口", "胸疼", "胸部疼痛",
    "呼吸困难", "气短", "心悸",
    "头痛", "腹痛", "肚子疼", "肚子痛", "背痛", "呕吐", "发热", "头晕",
)

AGGRAVATORS: tuple[str, ...] = (
    "剧烈", "压榨", "撕裂", "刀割", "绞痛",
    "持续不缓解", "一直不缓解", "越来越重", "逐渐加重", "明显加重",
    "疼得厉害", "痛得厉害", "疼醒", "痛醒", "受不了",
    "伴出汗", "伴大汗", "大汗淋漓", "冒冷汗", "脸色苍白", "面色苍白",
    "濒死", "说不出话", "无法说话", "意识模糊", "站不稳",
)

# 自杀/自残等心理危机关键词，需要更温柔但同样紧迫的引导。
CRISIS_KEYWORDS: tuple[str, ...] = (
    "自杀", "自残", "轻生", "不想活", "活不下去", "结束生命",
    "割腕", "跳楼", "烧炭", "想死", "寻死",
)

# ---------------------------------------------------------------------------
# 语境过滤词表
# ---------------------------------------------------------------------------
# 求知型提问标志：用户是在「问知识」，不是在「报症状」。
INQUIRY_MARKERS: tuple[str, ...] = (
    "如何预防", "怎么预防", "怎样预防", "如何避免", "怎么避免", "怎样避免",
    "如何判断", "怎么判断", "如何区分", "怎么区分", "如何辨别", "怎么辨别",
    "什么原因", "是什么原因", "什么引起的", "为什么会得", "为什么得",
    "有哪些症状", "有什么症状", "有什么表现", "有哪些表现",
    "如何治疗", "怎么治疗", "能不能治好", "能治好吗",
    "介绍一下", "了解一下", "科普", "我想知道", "想问一下", "解释一下",
)

# 否定标志：用户明确表示「没有」该症状。
NEGATION_MARKERS: tuple[str, ...] = (
    "没有", "没", "不是", "不会", "未曾", "并没有", "已排除", "排除",
)

# 语境窗口：关键词前后各取多少字符判断语境。
_WINDOW = 15
# 否定窗口：只看关键词紧邻的前几个字符，避免误伤（如「无力感伴呼吸困难」）。
_NEGATION_WINDOW = 4


def _in_inquiry_context(text: str, idx: int, kw: str) -> bool:
    """关键词是否出现在「求知型提问」的语境里。"""
    seg = text[max(0, idx - _WINDOW) : idx + len(kw) + _WINDOW]
    return any(m in seg for m in INQUIRY_MARKERS)


def _is_negated(text: str, idx: int) -> bool:
    """关键词紧邻前方是否有否定词。"""
    prefix = text[max(0, idx - _NEGATION_WINDOW) : idx]
    return any(m in prefix for m in NEGATION_MARKERS)


def _find(text: str, keyword: str) -> int:
    """返回关键词位置；若被否定或处于求知语境则返回 -1。"""
    idx = text.find(keyword)
    if idx == -1:
        return -1
    if _is_negated(text, idx):
        return -1
    if _in_inquiry_context(text, idx, keyword):
        return -1
    return idx


def detect_emergency(text: str) -> str | None:
    """检测文本中是否包含紧急症状，返回命中的关键词（用于提示），否则返回 None。

    长关键词优先匹配，避免「心梗」之类被更短的词抢先。
    """
    if not text:
        return None

    # 一级：单独出现即触发
    for kw in sorted(EMERGENCY_KEYWORDS, key=len, reverse=True):
        if _find(text, kw) != -1:
            return kw

    # 二级：症状 + 加重修饰词同现才触发
    for kw in SEVERE_SYMPTOMS:
        idx = _find(text, kw)
        if idx == -1:
            continue
        seg = text[max(0, idx - _WINDOW) : idx + len(kw) + _WINDOW]
        for agg in AGGRAVATORS:
            if agg in seg:
                return f"{kw}+{agg}"

    return None


def detect_crisis(text: str) -> str | None:
    """检测心理危机相关内容，返回命中的关键词，否则返回 None。"""
    if not text:
        return None
    for kw in CRISIS_KEYWORDS:
        if text.find(kw) != -1:
            return kw
    return None


